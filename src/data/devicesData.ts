export type DeviceCategory = "phone" | "laptop" | "tablet" | "watch";
export type PerformanceTier = "S" | "A" | "B" | "C" | "D";

export interface DeviceSpec {
  id: string;
  name: string;
  brand: string;
  category: DeviceCategory;
  releaseYear: number;
  releaseDate: string;
  priceGuide: string;
  avatarUrl: string;
  tagline: string;
  highlightBadges: string[];
  
  // 性能跑分体系与梯队评级 (S / A / B / C / D)
  performanceTier: PerformanceTier;
  overallScore: number; // 0 - 10000 标准化综合天梯指数
  geekbenchSingle: number; // Geekbench 6 单核
  geekbenchMulti: number; // Geekbench 6 多核
  graphicsBenchmark: {
    name: string; // "AnTuTu V10 GPU" | "3DMark TimeSpy" | "GFXBench Aztec"
    score: number;
    unit: string;
  };
  efficiencyRating: PerformanceTier;

  // 六维战力雷达图 (0 - 100)
  radarDimensions: {
    cpu: number;        // 算力性能
    gpu: number;        // 图形渲染
    display: number;    // 屏幕素质
    camera: number;     // 影像传感
    battery: number;    // 续航快充
    craftsmanship: number; // 做工便携
  };

  // 详细核心参数 (客观、丰富、无冗余夸大词)
  specs: {
    // 芯片与算力
    socName: string;
    processNode: string;
    cpuArchitecture: string;
    gpuModel: string;
    npuPerformance: string;
    
    // 屏幕显示
    screenSize: string;
    screenType: string;
    resolution: string;
    pixelDensity: string;
    refreshRate: string;
    peakBrightness: string;
    colorGamut: string;

    // 内存与存储
    ramOptions: string;
    storageOptions: string;
    expandable: string;

    // 影像系统
    mainCamera: string;
    telephotoCamera: string;
    ultraWideCamera: string;
    frontCamera: string;
    videoCapabilities: string;

    // 电池与补能
    batteryCapacity: string;
    wiredCharging: string;
    wirelessCharging: string;
    batteryLifeEst: string;

    // 外观与材质
    dimensions: string;
    weight: string;
    materials: string;
    waterResistance: string;

    // 连接与通信
    connectivity: string;
    biometrics: string;
    osVersion: string;
  };

  // 数据来源开源站点引用与溯源
  dataSource?: {
    provider: string; // 如 "GSMArena", "Primate Labs Geekbench", "UL 3DMark"
    sourceUrl: string;
    lastSynced: string;
    isLiveSynced?: boolean;
  };
}

